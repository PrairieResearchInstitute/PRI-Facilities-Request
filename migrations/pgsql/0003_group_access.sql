-- 0003_group_access.sql: authority from campus groups (owner, 2026-10-12: "we
-- will be using netid to determine the level of authority for user groups
-- across the board").
--
-- Identity comes from the university's authenticating proxy as a NetID
-- (facilities/lib/identity.php). Authority comes from three places, all keyed
-- by NetID or by campus group, never by a local user name:
--   work.app_users.role          one role per NetID (staff, coordinator, approver, admin)
--   work.app_adminaccess         access functions granted to one NetID, per survey
--   work.app_groupaccess (new)   a role or an access function granted to every
--                                member of a campus group the proxy names
-- facilities/lib/auth.php and access.php merge the three for the person
-- signed in; every existing permission check reads the merged result.
--
-- Work only: auth.php and access.php read authority from the Work register.
-- No SQL Server twin exists: LocalDB is the rollback, has no proxy and so no
-- groups. Rows are switched off (isactive = 0), never deleted, so the table
-- keeps the record of who granted what. tools/identity_seed.php writes it.
CREATE TABLE work.app_groupaccess (
    groupaccessid integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    groupname public.citext NOT NULL CHECK (char_length(groupname) BETWEEN 1 AND 256),
    surveycode public.citext CHECK (char_length(surveycode) <= 10),
    accessfunction public.citext CHECK (accessfunction IN ('director', 'proxy', 'facilities', 'safety', 'fleet', 'equipment', 'inventory', 'it', 'finance', 'deputy', 'executive', 'studio')),
    role public.citext CHECK (role IN ('coordinator', 'approver', 'admin')),
    note public.citext CHECK (char_length(note) <= 200),
    isactive smallint NOT NULL DEFAULT 1 CHECK (isactive IN (0, 1)),
    grantedat timestamp(6) NOT NULL DEFAULT CAST(statement_timestamp() AS timestamp(6)),
    grantedbynetid public.citext CHECK (char_length(grantedbynetid) <= 64),
    PRIMARY KEY (groupaccessid),
    -- Each row grants exactly one thing: a role or an access function.
    CHECK ((accessfunction IS NULL) <> (role IS NULL)),
    -- A role holds across the whole system; only a function is per survey.
    CHECK (role IS NULL OR surveycode IS NULL)
);
CREATE UNIQUE INDEX app_groupaccess_ux_grant ON work.app_groupaccess
    (groupname, COALESCE(surveycode, ''), COALESCE(accessfunction, ''), COALESCE(role, ''));
CREATE INDEX app_groupaccess_ix_group ON work.app_groupaccess (groupname, isactive);
