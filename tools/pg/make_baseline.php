<?php
declare(strict_types=1);

/**
 * Writes the PostgreSQL baseline and the runtime catalogue from the
 * SQL Server column model (tools/pg/tsql_model.php) and the register
 * manifest (tools/pg/registers.json).
 *
 *   php tools/pg/make_baseline.php           write both files
 *   php tools/pg/make_baseline.php --check   exit 1 when either file differs
 *                                            from what the model gives now
 *
 * Output:
 *   migrations/pgsql/0001_baseline.sql   one schema per register, the tables
 *                                        that register holds on LocalDB
 *   facilities/lib/pg_catalog.php        table and column names in their
 *                                        SQL Server spelling, for the
 *                                        translation layer and the loader
 *
 * The baseline is frozen once applied anywhere (drez-append-only-migrations):
 * after that, a schema change is a new numbered file in migrations/pgsql,
 * and --check is expected to report the baseline as different. Until then
 * the file is regenerated, never hand-edited.
 *
 * Type translation, faithful first (drez-sqlite-to-postgres-port rule 11):
 *   NVARCHAR(n)    citext plus CHECK (char_length(col) <= n). SQL Server's
 *                  default collation compares case-insensitively, in =,
 *                  LIKE, ORDER BY, GROUP BY and UNIQUE alike; citext keeps
 *                  all of them, and the check keeps the length limit.
 *   NVARCHAR(MAX)  citext
 *   INT, BIGINT    integer, bigint; IDENTITY becomes GENERATED BY DEFAULT
 *                  AS IDENTITY so the loader can keep the original ids
 *   BIT            smallint (the code compares with 1 and 0)
 *   DECIMAL(p,s)   numeric(p,s)
 *   DATETIME2      timestamp(6) without time zone (SQL Server stamped local
 *                  time; each connection sets the application time zone)
 *   DATE           date
 * Foreign keys are created only inside a register, and only where the
 * LocalDB database has them: Work, Move and Shop ran the scripts, so every
 * key whose target is in the same database; the other seven received
 * scaffolding as copies without keys, and keys only on the tables they own.
 */

require_once __DIR__ . '/tsql_model.php';
require_once __DIR__ . '/../../facilities/lib/db.php';

const PG_SCRIPT_REGISTERS = ['work', 'move', 'shop'];

function pgb_root(): string
{
    return dirname(__DIR__, 2);
}

function pgb_ident(string $s): string
{
    return strtolower($s);
}

/** SQL Server 'app.Settings' to PostgreSQL table name 'app_settings'. */
function pgb_table(string $q): string
{
    return strtolower(str_replace('.', '_', $q));
}

function pgb_type(array $col): array
{
    $t = $col['type'];
    if (preg_match('/^N?VARCHAR\((\d+)\)$|^N?CHAR\((\d+)\)$/', $t, $m)) {
        return ['public.citext', (int)($m[1] !== '' ? $m[1] : $m[2])];
    }
    if (preg_match('/^N?VARCHAR\(MAX\)$|^N?TEXT$/', $t)) {
        return ['public.citext', null];
    }
    if (preg_match('/^(DECIMAL|NUMERIC)\((\d+),(\d+)\)$/', $t, $m)) {
        return ["numeric({$m[2]},{$m[3]})", null];
    }
    $map = ['INT' => 'integer', 'BIGINT' => 'bigint', 'SMALLINT' => 'smallint', 'TINYINT' => 'smallint',
            'BIT' => 'smallint', 'DATE' => 'date', 'DATETIME2' => 'timestamp(6)', 'DATETIME' => 'timestamp(6)',
            'REAL' => 'real', 'FLOAT' => 'double precision', 'MONEY' => 'numeric(19,4)', 'TIME' => 'time',
            'SYSNAME' => 'public.citext'];
    $base = preg_replace('/\(.*$/', '', $t);
    if (!isset($map[$base])) {
        throw new RuntimeException('No PostgreSQL type for ' . $t);
    }
    return [$map[$base], $base === 'SYSNAME' ? 128 : null];
}

function pgb_default(string $d): string
{
    $u = strtoupper(trim($d));
    while (preg_match('/^\((.*)\)$/s', $u) && substr_count($u, '(') === substr_count($u, ')')) {
        $u = substr($u, 1, -1);
        $d = substr(trim($d), 1, -1);
    }
    if (in_array($u, ['SYSDATETIME()', 'GETDATE()', 'CURRENT_TIMESTAMP'], true)) {
        return 'CAST(statement_timestamp() AS timestamp(6))';
    }
    if (preg_match('/^CAST\((SYSDATETIME|GETDATE)\(\) AS DATE\)$/', $u)) {
        return 'CURRENT_DATE';
    }
    if (preg_match("/^-?\\d+(\\.\\d+)?$/", $u) || preg_match("/^'([^']|'')*'$/", trim($d)) || $u === 'NULL') {
        return trim($d);
    }
    throw new RuntimeException('No PostgreSQL default for ' . $d);
}

/** A CHECK expression: identifiers fold to lower case; no T-SQL functions appear. */
function pgb_check(string $e): string
{
    if (preg_match('/\b(LEN|ISNULL|GETDATE|SYSDATETIME|CHARINDEX)\s*\(/i', $e)) {
        throw new RuntimeException('Check needs translating: ' . $e);
    }
    return $e;
}

function pgb_name(string ...$parts): string
{
    $n = strtolower(implode('_', $parts));
    $n = preg_replace('/[^a-z0-9_]/', '_', $n);
    if (strlen($n) > 63) {
        $n = substr($n, 0, 54) . '_' . substr(md5($n), 0, 8);
    }
    return $n;
}

function pgb_homes(array $registers): array
{
    $count = [];
    foreach ($registers as $r => $tables) {
        foreach ($tables as $t) {
            $count[$t][] = $r;
        }
    }
    $home = [];
    foreach ($count as $t => $rs) {
        if (isset(APP_TABLE_HOME[$t])) {
            $home[$t] = APP_TABLE_HOME[$t];
        } elseif (count($rs) === 1) {
            $home[$t] = $rs[0];
        }
    }
    return $home;
}

/** Order tables so every in-register key target comes first. */
function pgb_order(array $tables, array $model, callable $fkTargets): array
{
    $done = [];
    $out = [];
    $visit = function (string $t, array $stack) use (&$visit, &$done, &$out, $fkTargets, $tables) {
        if (isset($done[$t])) {
            return;
        }
        if (isset($stack[$t])) {
            return;                                   // self or cyclic key: order does not matter
        }
        $stack[$t] = true;
        foreach ($fkTargets($t) as $dep) {
            if ($dep !== $t && in_array($dep, $tables, true)) {
                $visit($dep, $stack);
            }
        }
        $done[$t] = true;
        $out[] = $t;
    };
    foreach ($tables as $t) {
        $visit($t, []);
    }
    return $out;
}

function pgb_build(): array
{
    $warn = [];
    $model = tsql_model(null, $warn);
    $man = json_decode((string)file_get_contents(__DIR__ . '/registers.json'), true);
    $registers = $man['registers'];
    $homes = pgb_homes($registers);
    $sql = [];
    $sql[] = '-- 0001_baseline.sql: PRI Facilities Request on PostgreSQL.';
    $sql[] = '-- Generated by tools/pg/make_baseline.php from sql/00 to sql/35 and tools/pg/registers.json.';
    $sql[] = '-- Never edit by hand; once applied anywhere, never edit at all: add 0002 instead.';
    $sql[] = '-- One schema per register. No foreign key crosses a schema (platform D-027, owner 2026-10-04).';
    $sql[] = '';
    $sql[] = 'CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public;';
    $sql[] = '';
    $catalogTables = [];
    $fksAll = [];
    foreach ($registers as $reg => $tables) {
        $sql[] = '-- ==== register ' . $reg . ' (' . APP_DB_LABELS[$reg] . ') ====';
        $sql[] = 'CREATE SCHEMA ' . $reg . ';';
        $keysHere = function (string $t) use ($reg, $homes, $model, $tables): array {
            $out = [];
            if (!in_array($reg, PG_SCRIPT_REGISTERS, true) && ($homes[$t] ?? null) !== $reg) {
                return [];
            }
            foreach ($model[$t]['fks'] as $fk) {
                $target = tsql_find(array_flip($tables), $fk['ref']);
                if ($target !== null) {
                    $out[] = ['fk' => $fk, 'target' => $target];
                }
            }
            return $out;
        };
        $targets = function (string $t) use ($keysHere): array {
            return array_map(fn($k) => $k['target'], $keysHere($t));
        };
        foreach (pgb_order($tables, $model, $targets) as $t) {
            if (!isset($model[$t])) {
                throw new RuntimeException("$reg holds $t, which no script creates");
            }
            $tbl = $model[$t];
            $pgt = $reg . '.' . pgb_table($t);
            $lines = [];
            foreach ($tbl['columns'] as $c => $col) {
                [$type, $len] = pgb_type($col);
                $l = '    ' . pgb_ident($c) . ' ';
                if ($col['identity']) {
                    $l .= ($type === 'bigint' ? 'bigint' : 'integer') . ' GENERATED BY DEFAULT AS IDENTITY';
                } else {
                    $l .= $type;
                }
                if (!$col['null']) {
                    $l .= ' NOT NULL';
                }
                if ($col['default'] !== null) {
                    $l .= ' DEFAULT ' . pgb_default($col['default']);
                }
                if ($len !== null) {
                    $l .= ' CHECK (char_length(' . pgb_ident($c) . ') <= ' . $len . ')';
                }
                $lines[] = $l;
            }
            if ($tbl['pk']) {
                $lines[] = '    PRIMARY KEY (' . implode(', ', array_map('pgb_ident', $tbl['pk'])) . ')';
            }
            foreach ($tbl['uniques'] as $u) {
                $lines[] = '    UNIQUE (' . implode(', ', array_map('pgb_ident', $u['cols'])) . ')';
            }
            foreach ($tbl['checks'] as $ck) {
                $lines[] = '    CHECK (' . pgb_check($ck['expr']) . ')';
            }
            $sql[] = 'CREATE TABLE ' . $pgt . " (\n" . implode(",\n", $lines) . "\n);";
            foreach ($tbl['indexes'] as $iname => $ix) {
                $cols = array_map(fn($c) => preg_replace_callback('/^\w+/', fn($m) => pgb_ident($m[0]), $c), $ix['cols']);
                $s = 'CREATE ' . ($ix['unique'] ? 'UNIQUE ' : '') . 'INDEX ' . pgb_name(pgb_table($t), $iname)
                   . ' ON ' . $pgt . ' (' . implode(', ', $cols) . ')';
                if ($ix['include']) {
                    $s .= ' INCLUDE (' . implode(', ', array_map('pgb_ident', $ix['include'])) . ')';
                }
                if ($ix['where'] !== null) {
                    $s .= ' WHERE ' . pgb_check($ix['where']);
                }
                $sql[] = $s . ';';
            }
            foreach ($keysHere($t) as $k) {
                $fk = $k['fk'];
                $refcols = $fk['refcols'] ?: $model[$k['target']]['pk'];
                $s = 'ALTER TABLE ' . $pgt . ' ADD FOREIGN KEY (' . implode(', ', array_map('pgb_ident', $fk['cols']))
                   . ') REFERENCES ' . $reg . '.' . pgb_table($k['target'])
                   . ' (' . implode(', ', array_map('pgb_ident', $refcols)) . ')';
                if ($fk['onDelete'] !== null && $fk['onDelete'] !== 'NO ACTION') {
                    $s .= ' ON DELETE ' . $fk['onDelete'];
                }
                $fksAll[] = $s . ' DEFERRABLE INITIALLY IMMEDIATE;';
            }
            $catalogTables[$t] = array_keys($tbl['columns']);
        }
        $sql[] = '';
    }
    $sql[] = '-- ==== foreign keys, inside each register only ====';
    foreach ($fksAll as $s) {
        $sql[] = $s;
    }
    $sql[] = '';

    // The catalogue.
    $names = [];
    foreach ($catalogTables as $t => $cols) {
        foreach ($cols as $c) {
            $names[strtolower($c)] = $c;
        }
    }
    ksort($names);
    $tables = [];
    foreach ($catalogTables as $t => $cols) {
        $tables[$t] = $cols;
    }
    ksort($tables);
    $ident = [];
    foreach ($model as $t => $tbl) {
        foreach ($tbl['columns'] as $c => $col) {
            if ($col['identity']) {
                $ident[$t] = $c;
            }
        }
    }
    ksort($ident);
    $php = "<?php\ndeclare(strict_types=1);\n\n"
         . "/**\n * Table and column names in their SQL Server spelling, for the PostgreSQL\n"
         . " * translation layer (pgsql.php) and the loader (tools/pg/load.php).\n"
         . " * Generated by tools/pg/make_baseline.php; never edit by hand.\n */\n\n"
         . "/** Which tables each register schema holds. */\n"
         . 'const PG_REGISTER_TABLES = ' . pgb_export($registers) . ";\n\n"
         . "/** Every table, with its columns in order. */\n"
         . 'const PG_TABLE_COLUMNS = ' . pgb_export($tables) . ";\n\n"
         . "/** The identity column of each table that has one. */\n"
         . 'const PG_IDENTITY_COLUMNS = ' . pgb_export($ident) . ";\n\n"
         . "/** Lower-case column name to its SQL Server spelling. */\n"
         . 'const PG_COLUMN_NAMES = ' . pgb_export($names) . ";\n";
    return ['sql' => implode("\n", $sql), 'php' => $php, 'notes' => $warn];
}

function pgb_export(array $a): string
{
    $isList = array_is_list($a);
    $parts = [];
    foreach ($a as $k => $v) {
        $val = is_array($v) ? pgb_export($v) : var_export($v, true);
        $parts[] = $isList ? $val : var_export($k, true) . ' => ' . $val;
    }
    $one = '[' . implode(', ', $parts) . ']';
    if (strlen($one) < 100 && !preg_match('/\n/', $one)) {
        return $one;
    }
    return "[\n    " . implode(",\n    ", array_map(fn($p) => str_replace("\n", "\n    ", $p), $parts)) . ",\n]";
}

if (PHP_SAPI === 'cli' && realpath($_SERVER['SCRIPT_FILENAME'] ?? '') === __FILE__) {
    $out = pgb_build();
    $files = [
        pgb_root() . '/migrations/pgsql/0001_baseline.sql' => $out['sql'],
        pgb_root() . '/facilities/lib/pg_catalog.php' => $out['php'],
    ];
    if (in_array('--check', $argv, true)) {
        $bad = 0;
        foreach ($files as $f => $content) {
            $have = is_file($f) ? str_replace("\r\n", "\n", (string)file_get_contents($f)) : null;
            if ($have !== $content) {
                echo 'DIFFERS ' . basename($f) . "\n";
                $bad++;
            }
        }
        echo $bad ? "baseline check: $bad file(s) differ from the model\n" : "baseline check: both files match the model\n";
        exit($bad ? 1 : 0);
    }
    foreach ($files as $f => $content) {
        if (!is_dir(dirname($f))) {
            mkdir(dirname($f), 0777, true);
        }
        file_put_contents($f, $content);
        echo 'wrote ' . str_replace('\\', '/', substr($f, strlen(pgb_root()) + 1)) . ' (' . strlen($content) . " bytes)\n";
    }
    foreach ($out['notes'] as $n) {
        echo "note: $n\n";
    }
}
